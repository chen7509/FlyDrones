"""Assemble a non-admitted build request from saved declarations, without production imports.

Windows/local artifact preparation only. No target paths are opened/stat'ed/resolved;
no existing payload/blob/archive is read or rehashed. Outputs are exclusive new files.
"""

import ast
import hashlib
import json
from pathlib import Path, PurePosixPath


ROOT = Path(__file__).absolute().parents[2]
OUTPUT = Path(__file__).absolute().parent
BASE = "results/native-linux-production-inputs-20261019"
PLAN = "results/native-fresh-build-admission-plan-20261020/proposal.json"
UPSTREAM_MANIFEST = "results/native-offset-run-plan-20261018/upstream-build-source-manifest.json"


def pairs(items):
    result = {}
    for key, value in items:
        if key in result:
            raise ValueError("duplicate JSON key: " + key)
        result[key] = value
    return result


def declaration(relative):
    return json.loads((ROOT / relative).read_text(encoding="utf-8-sig"), object_pairs_hook=pairs)


def save(name, value):
    raw = (json.dumps(value, ensure_ascii=False, indent=2, allow_nan=False) + "\n").encode("utf-8")
    with (OUTPUT / name).open("xb") as stream:
        stream.write(raw)
    # Only newly generated bytes are hashed; not an actual Linux file pin.
    return dict(file=name, bytes=len(raw), sha256=hashlib.sha256(raw).hexdigest())


def constants():
    tree = ast.parse((ROOT / "tools/benchmark/native_offset_once.py").read_text(encoding="utf-8-sig"))
    names = {"BUILD_KEYS", "SOURCE_NAMES", "COVERS", "UPSTREAM", "TARGET", "UPSTREAM_MANIFEST_SHA", "SCOPE_TOOLS"}
    result = {}
    for node in tree.body:
        if isinstance(node, ast.Assign) and len(node.targets) == 1 and isinstance(node.targets[0], ast.Name):
            name = node.targets[0].id
            if name in names:
                result[name] = ast.literal_eval(node.value)
    if set(result) != names:
        raise ValueError("source contract constants unavailable")
    return result


def main():
    plan = declaration(PLAN)
    refs = declaration(BASE + "/final-v3/input-pin-references.json")["files"]
    readbacks = declaration(BASE + "/final-receipt-bindings.json")
    sources = declaration(BASE + "/current-linux-source-manifest.json")
    groups = declaration(BASE + "/final-v3/header-package-manifest.json")["groups"]
    upstream = declaration(UPSTREAM_MANIFEST)
    c = constants()
    bindings = plan["binding_candidates"]
    if set(bindings) != set(c["BUILD_KEYS"]):
        raise ValueError("16-key binding selection differs")
    pins, provenance = {}, {}

    def add(name, pin, origin):
        if set(pin) != {"path", "resolved", "bytes", "sha256"} or pin["path"] != name:
            raise ValueError("invalid saved pin shape: " + name)
        if not all(PurePosixPath(pin[k]).is_absolute() for k in ("path", "resolved")):
            raise ValueError("nonabsolute saved Linux path")
        if type(pin["bytes"]) is not int or not 0 <= pin["bytes"] <= 67108864:
            raise ValueError("invalid saved pin length")
        if len(pin["sha256"]) != 64 or any(x not in "0123456789abcdef" for x in pin["sha256"]):
            raise ValueError("invalid saved digest")
        if name in pins and pins[name] != pin:
            raise ValueError("conflicting saved pin; no latest-wins merge: " + name)
        pins[name] = pin
        provenance.setdefault(name, []).append(origin)

    for name, row in refs.items():
        add(name, row["pin"], dict(declaration=BASE + "/final-v3/input-pin-references.json",
                                 phase=row["phase"], blob=row["blob"]))
    # Exactly the three required receipt/manifest files outside the sealed 3677 union.
    for key in ("current_linux_source_manifest", "toolchain_receipt", "header_package_manifest"):
        name = bindings[key]
        row = readbacks["files"][name]
        add(name, row["file_pin"], dict(declaration=BASE + "/final-receipt-bindings.json",
                                      phase=row["phase"], blob=row["blob"]))
    required12 = [bindings["deployed_repo"] + "/tools/benchmark/" + n for n in c["SOURCE_NAMES"]]
    required12 += [bindings["deployed_repo"] + "/tools/benchmark/native_offset_reset_v2/CMakeLists.txt"]
    assert all(sources["files"].get(name) == pins.get(name) for name in required12)
    assert len(sources["files"]) == 128 and all(pins.get(k) == v for k, v in sources["files"].items())
    assert len(upstream["files"]) == 143 and upstream["commit"] == c["UPSTREAM"]
    for name, expected in upstream["files"].items():
        pin = pins[bindings["upstream_source_tree"] + "/" + name]
        assert all(pin[k] == expected[k] for k in ("bytes", "sha256"))
    assert all(names and all(name in pins for name in names) for names in groups.values())
    assert all(name in pins for name in c["SCOPE_TOOLS"])
    directory_keys = {"deployed_repo", "upstream_source_tree", "eigen_config_dir", "opencv4_config_dir",
                      "boost_config_dir", "ceres_config_dir", "exclusive_build_dir"}
    binding_files = [bindings[k] for k in c["BUILD_KEYS"] if k not in directory_keys]
    assert len(binding_files) == 9 and all(p in pins for p in binding_files)
    manifest_path = bindings["deployed_repo"] + "/" + UPSTREAM_MANIFEST
    required = set(required12 + binding_files + list(c["SCOPE_TOOLS"]) + [manifest_path])
    missing = sorted(required - pins.keys())
    assert missing == [manifest_path]
    # Missing observed context is not manufactured from the contract's SHA constant.
    request = dict(
        schema="native-offset-fresh-source-request-v1", stage="build", build_profile="fixed-source-openvins-v1",
        target=c["TARGET"], upstream_commit=c["UPSTREAM"], bindings=bindings,
        input_pins=dict(sorted(pins.items())), build_environment=plan["build_environment_candidate"],
        link_resolutions={}, preparation_status="ASSEMBLED_FROM_SAVED_RECORDS_INCOMPLETE_NOT_ADMITTED",
        missing_required_input_pin_paths=missing, input_pins_are_cross_time_saved_observations=True,
        future_fresh_continuity_proven=False, build_environment_admitted=False,
        link_resolutions_complete=False, full_input_closure_complete=False, full_request_complete=False,
        admission_granted=False, decision=None, dispatchable=False, all_qualifications=False,
        runtime_graph_frozen=False, physical_dispatch_ready=False,
    )
    gaps = dict(
        schema="native-fresh-build-p1-precise-gaps-v1",
        selected_declaration_scope=[BASE + "/final-v3/input-pin-references.json", BASE + "/final-receipt-bindings.json"],
        pin_gaps=[dict(id="P1-M1", path=manifest_path, missing_fields=["actual-context path/resolved/bytes/sha256 pin and observation provenance"],
                      known_contract_sha256=c["UPSTREAM_MANIFEST_SHA"],
                      basis="Absent from the selected sealed union and readback sidecar, not a global absence claim",
                      no_bytes_sha_or_resolved_guessed=True)],
        non_pin_gaps=[
            dict(id="P1-R1", field="link_resolutions", status="EMPTY_NOT_COMPLETE", owner="P4",
                 exact_limit="Actual new link argv does not exist; no speculative -l names or NEEDED-to-driver resolution"),
            dict(id="P1-E1", field="build_environment", status="SELECTED_DECLARATION_NOT_ENVIRONMENT_PROOF", owner="P2",
                 selected=request["build_environment"]),
            dict(id="P1-F1", field="input_pins", status="SAVED_CROSS_TIME_NOT_FUTUREFRESH", owner="P2-P8",
                 exact_limit="No production verifier or current-path hash/identity revalidation was invoked"),
            dict(id="P1-A1", field="review", status="NOT_CREATED_NO_ALLOW_ONCE", owner="P8"),
        ],
        directory_binding_keys_are_not_missing_regular_file_pins=sorted(directory_keys),
        deferred_other_conditions=[dict(id=row["id"], status=row["status"]) for row in plan["pre_build_conditions"] if row["id"] != "P1"],
        post_build_outputs_not_required_as_preexisting_inputs=True,
        original_templates_unchanged=True, full_request_complete=False, dispatchable=False,
    )
    minimum = dict(
        schema="native-fresh-build-p1-next-minimum-scope-v1", status="PROPOSED_ONLY_NOT_AUTHORIZED_NOT_EXECUTED",
        scope_goal="Close only P1-M1 actual Linux manifest pin context, not all P2-P8",
        exact_target=manifest_path, target_count=1, known_contract_sha256=c["UPSTREAM_MANIFEST_SHA"],
        first_choice="Reuse an existing exact-path actual-Linux receipt if explicitly located in saved metadata; no broad search or old payload audit",
        if_no_reusable_receipt="Separately authorize one exact regular-file Linux context readback; known content reobservation, not new independent payload",
        constraints=["Current human forbids repeat collection: this proposal does not authorize that readback",
                     "No guessed resolved endpoint, byte length or Linux receipt from a known Windows SHA",
                     "No 128-source/143-source/header/compiler/library re-read or directory enumeration",
                     "No old library/build objects/logs, native once attempt probe, resources, configure/compiler/link/SDK/target",
                     "Use original observer caps without expansion; stop on mismatch, missing, redirect, partial, cap or cleanup unknown; no retry",
                     "One manifest pin closes only that exact gap; it grants no review or build/run permission"],
        subsequent_nonexecuting_scope="Then select the P2 host/WSL/environment declaration boundary from saved metadata; P4/P5/P6/P7/P8 remain separate",
        all_qualifications=False, dispatchable=False,
    )
    outputs = []
    outputs.append(save("request.json", request))
    outputs.append(save("input-pin-sources.json", dict(schema="saved-request-pin-provenance-v1", files=dict(sorted(provenance.items())),
                                                     payloads_rehashed=False, linux_paths_accessed=False)))
    outputs.append(save("missing-evidence.json", gaps))
    outputs.append(save("next-minimum-scope.json", minimum))
    summary = dict(
        schema="native-fresh-build-p1-assembly-summary-v1", source_head="b06f2746a38bfdd904f20a2a8b41d1dd936b73cf",
        status="P1_REQUEST_ASSEMBLED_INCOMPLETE_NOT_ADMITTED", request_schema=request["schema"], stage="build",
        saved_union_pin_paths=len(refs), required_receipt_file_pins_added=3, assembled_input_pin_paths=len(pins),
        required_binding_keys=16, required_binding_file_pins_present=9, directory_binding_keys=7,
        local_source_pins=128, required_once_source_pins=12, upstream_source_pins=143,
        named_group_entries={k: len(v) for k, v in groups.items()}, missing_required_pin_paths=missing,
        saved_source_field_mismatches=0, saved_upstream_sha_size_mismatches=0, saved_group_missing_pin_paths=0,
        saved_pin_conflicts=0, generated_outputs=outputs,
        request_sha_is_only_new_local_bytes_not_linux_readback=True,
        no_production_import_verify_or_once=True, no_existing_payload_hash_or_archive_audit=True,
        no_linux_resources_compiler_configure_link_target_sdk_or_tests=True,
        original_attempt_not_created_or_probed=True, full_request_complete=False,
        full_input_closure_complete=False, all_qualifications=False, dispatchable=False,
    )
    save("assembly-summary.json", summary)
    print(json.dumps({k: summary[k] for k in ("status", "assembled_input_pin_paths", "missing_required_pin_paths")}, ensure_ascii=True))


if __name__ == "__main__":
    main()
